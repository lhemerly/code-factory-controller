import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
spec=importlib.util.spec_from_file_location('acceptance',Path(__file__).with_name('goal-acceptance.py'))
a=importlib.util.module_from_spec(spec);spec.loader.exec_module(a)
class Tests(unittest.TestCase):
 def test_missing_suite_never_passes(self):
  self.assertEqual(a.run_acceptance({},'unused','a'*40)['status'],'awaiting_acceptance')
 def test_vulkan_requires_actual_dispatch_evidence(self):
  check={'evidence_type':'vulkan_execution'}
  e={'passed':True,'commit':'a'*40,'evidence_type':'vulkan_execution','gpu_dispatches':0,'validation_passed':True,'device':{'name':'fixture','vendor_id':1,'device_id':2}}
  with self.assertRaises(ValueError):a.validate_evidence(e,check,'a'*40)
  e['gpu_dispatches']=1
  self.assertEqual(a.validate_evidence(e,check,'a'*40),e)
  e['skipped']=True
  with self.assertRaises(ValueError):a.validate_evidence(e,check,'a'*40)
 def test_wrong_commit_or_device_rejected(self):
  e={'passed':True,'commit':'b'*40,'evidence_type':'vulkan_execution','gpu_dispatches':1,'validation_passed':True,'device':{}}
  with self.assertRaises(ValueError):a.validate_evidence(e,{'evidence_type':'vulkan_execution'},'a'*40)
 def test_real_command_failure_and_clean_checkout(self):
  with tempfile.TemporaryDirectory() as d:
   root=Path(d);repo=root/'repo';repo.mkdir()
   subprocess.run(['git','init','-q',str(repo)],check=True)
   subprocess.run(['git','-c','user.name=Test','-c','user.email=test@example.invalid','commit','--allow-empty','-qm','base'],cwd=repo,check=True)
   commit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=repo,text=True).strip()
   # Output generated by a test fixture, not evidence of hardware execution.
   code="import os,json;assert 'FACTORY_OPERATOR_TOKEN' not in os.environ;print(json.dumps({'passed':True,'commit':os.environ['FACTORY_VERIFICATION_COMMIT'],'evidence_type':'cpu_tests'}))"
   manifest={'repository':str(repo),'required_evidence':['cpu_tests'],'completion_checks':[{'id':'cpu','evidence_type':'cpu_tests','argv':[sys.executable,'-c',code]}]}
   self.assertTrue(a.run_acceptance(manifest,root/'state',commit)['passed'])
   manifest['completion_checks'][0]['argv']=[sys.executable,'-c','raise SystemExit(7)']
   result=a.run_acceptance(manifest,root/'state',commit)
   self.assertEqual(result['status'],'acceptance_failed');self.assertEqual(result['receipts'][0]['exit_status'],7)
 def test_cpu_suite_cannot_cover_vulkan_requirement(self):
  m={'required_evidence':['vulkan_execution'],'completion_checks':[{'evidence_type':'cpu_tests'}]}
  self.assertEqual(a.run_acceptance(m,'unused','a'*40)['status'],'awaiting_acceptance')
if __name__=='__main__':unittest.main()
