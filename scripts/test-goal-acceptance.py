class AcceptanceFailureTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.repo = self.root / 'repo'
        self.repo.mkdir()
        subprocess.run(['git', 'init', '-q', str(self.repo)], check=True)
        subprocess.run(['git', '-c', 'user.name=Test', '-c', 'user.email=test@example.invalid',
                        'commit', '--allow-empty', '-qm', 'base'], cwd=self.repo, check=True)
        self.commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=self.repo, text=True).strip()
        self.manifest = {'repository': str(self.repo), 'required_evidence': ['cpu_tests'],
                         'completion_checks': [{'id': 'cpu', 'evidence_type': 'cpu_tests',
                                                'argv': [sys.executable, '-c', 'print("{}")']}]}

    def run_manifest(self):
        return a.run_acceptance(self.manifest, self.root / 'state', self.commit)

    def test_non_object_evidence_is_a_failed_receipt(self):
        for value in [[], None, True, 12, 'text']:
            with self.subTest(value=value):
                self.manifest['completion_checks'][0]['argv'] = [sys.executable, '-c', f'print({json.dumps(value)!r})']
                result = self.run_manifest()
                self.assertEqual(result['status'], 'acceptance_failed')
                self.assertEqual(result['phase'], 'check_evidence')
                self.assertIn('JSON object', result['reason'])
                self.assertEqual(result['receipts'][0]['exit_status'], 0)

    def test_missing_executable_retains_launch_failure_receipt(self):
        self.manifest['completion_checks'][0]['argv'] = [str(self.root / 'missing-command')]
        result = self.run_manifest()
        self.assertEqual(result['status'], 'acceptance_failed')
        self.assertEqual(result['phase'], 'check_launch')
        self.assertEqual(result['error_type'], 'FileNotFoundError')
        self.assertIsNone(result['receipts'][0]['exit_status'])
        self.assertTrue(Path(result['receipts'][0]['stderr']).exists())
        self.assertIn('retry_guidance', result)

    def test_unavailable_repository_and_missing_git_return_setup_failure(self):
        self.manifest['repository'] = str(self.root / 'missing-repository')
        result = self.run_manifest()
        self.assertEqual(result['status'], 'acceptance_failed')
        self.assertEqual(result['phase'], 'setup')
        self.assertNotEqual(result['setup'][0]['exit_status'], 0)
        self.assertTrue(Path(result['setup'][0]['stderr']).read_text())
        self.manifest['verification_environment'] = {'PATH': str(self.root / 'no-tools')}
        result = self.run_manifest()
        self.assertEqual(result['phase'], 'setup')
        self.assertEqual(result['error_type'], 'FileNotFoundError')

    def test_missing_commit_and_unwritable_output_return_setup_failure(self):
        result = a.run_acceptance(self.manifest, self.root / 'state', '0' * 40)
        self.assertEqual(result['status'], 'acceptance_failed')
        self.assertEqual(result['setup'][-1]['stage'], 'checkout')
        self.assertNotEqual(result['setup'][-1]['exit_status'], 0)
        (self.root / 'blocked.acceptance').write_text('not a directory')
        result = a.run_acceptance(self.manifest, self.root / 'blocked', self.commit)
        self.assertEqual(result['status'], 'acceptance_failed')
        self.assertEqual(result['phase'], 'setup')

    def test_timeout_retains_failed_execution_evidence(self):
        self.manifest['completion_checks'][0].update({
            'argv': [sys.executable, '-c', 'import time; time.sleep(30)'], 'timeout_seconds': 1})
        result = self.run_manifest()
        self.assertEqual(result['status'], 'acceptance_failed')
        self.assertEqual(result['phase'], 'check_evidence')
        self.assertIn('timeout', result['reason'])
        self.assertNotEqual(result['receipts'][0]['exit_status'], 0)

if __name__=='__main__':unittest.main()
